// Deploys the how-to-watch-live Worker. Run by build\deploy-how-to-watch-live.bat
// from the worker\ folder; uses the machine's normal `wrangler login`, no
// tokens or secrets.
//
//   1. checks wrangler is installed and logged in (opens the login page if not);
//   2. finds the KV namespace "how-to-watch-live", creating it the first time;
//   3. writes wrangler.deploy.toml (git-ignored) = wrangler.toml + that id;
//   4. wrangler deploy --config wrangler.deploy.toml;
//   5. asks https://hoopsmatic.com/how-to-watch/live/run for a first refresh
//      and prints, in plain words, whether the live pages can read from it.

import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';

const TITLE = 'how-to-watch-live';
const STATUS_URL = 'https://hoopsmatic.com/how-to-watch/live/run';

function step(text) { console.log(`\n== ${text}`); }
function fail(text) { console.error(`\nSTOPPED: ${text}`); process.exit(1); }

function wrangler(args, { quiet = false } = {}) {
  return execSync(`wrangler ${args}`, {
    encoding: 'utf8',
    // stdin ignored so no command waits on a question; output captured when quiet.
    stdio: quiet ? ['ignore', 'pipe', 'pipe'] : ['ignore', 'inherit', 'inherit'],
  });
}

function listNamespaces() {
  const out = wrangler('kv namespace list', { quiet: true });
  const start = out.indexOf('['), end = out.lastIndexOf(']');
  if (start < 0 || end < start) fail('could not read the KV namespace list from wrangler.');
  return JSON.parse(out.slice(start, end + 1));
}

function findNamespace() {
  return listNamespaces().find((ns) => ns.title === TITLE || ns.title.endsWith('-' + TITLE));
}

step('Checking wrangler');
try {
  console.log(wrangler('--version', { quiet: true }).trim());
} catch (e) {
  fail('wrangler is not installed. Install it once with: npm install -g wrangler');
}
let who = '';
try { who = wrangler('whoami', { quiet: true }); } catch (e) { who = ''; }
if (!/logged in/i.test(who) || /not authenticated|not logged in/i.test(who)) {
  console.log('Not logged in to Cloudflare. A browser window opens for the usual login.');
  execSync('wrangler login', { stdio: 'inherit' });
}

// A login that sees more than one Cloudflare account makes wrangler refuse to
// guess. Ask once which one is HoopsMatic's and remember it on this machine
// only (.account-id is git-ignored; it is an account id, not a key).
if (existsSync('.account-id')) process.env.CLOUDFLARE_ACCOUNT_ID = readFileSync('.account-id', 'utf8').trim();
function accounts() {
  const rows = [];
  for (const line of who.split(/\r?\n/)) {
    const m = /│\s*(.+?)\s*│\s*([0-9a-f]{32})\s*│/.exec(line);
    if (m) rows.push({ name: m[1], id: m[2] });
  }
  return rows;
}
if (!process.env.CLOUDFLARE_ACCOUNT_ID) {
  try { who = wrangler('whoami', { quiet: true }); } catch (e) { /* keep the first answer */ }
  const list = accounts();
  if (list.length > 1) {
    console.log('Your Cloudflare login can use more than one account:');
    list.forEach((a, i) => console.log(`  ${i + 1}. ${a.name}`));
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const pick = Number((await rl.question('Number of the account that holds hoopsmatic.com: ')).trim());
    rl.close();
    if (!list[pick - 1]) fail('no account picked.');
    process.env.CLOUDFLARE_ACCOUNT_ID = list[pick - 1].id;
    writeFileSync('.account-id', list[pick - 1].id + '\n');
    console.log(`Using "${list[pick - 1].name}" (remembered for next time).`);
  }
}

step('Finding the KV store');
let ns = findNamespace();
if (!ns) {
  console.log(`Creating the KV store "${TITLE}" (first deploy only).`);
  wrangler(`kv namespace create ${TITLE}`);
  ns = findNamespace();
  if (!ns) fail('the KV store was created but could not be found afterwards.');
}
console.log(`Using KV store "${ns.title}".`);

step('Writing wrangler.deploy.toml');
const base = readFileSync('wrangler.toml', 'utf8');
writeFileSync('wrangler.deploy.toml',
  `# Generated by scripts/deploy.mjs. Do not commit.\n${base}\n[[kv_namespaces]]\nbinding = "LIVE_KV"\nid = "${ns.id}"\n`);

step('Deploying');
try {
  wrangler('deploy --config wrangler.deploy.toml');
} catch (e) {
  fail('wrangler deploy failed. Scroll up for its message.');
}

step('First refresh and check');
let status = null;
for (let attempt = 1; attempt <= 8 && !status; attempt++) {
  try {
    const r = await fetch(`${STATUS_URL}?t=${Date.now()}`, { headers: { 'Cache-Control': 'no-cache' } });
    const type = r.headers.get('content-type') || '';
    if (r.ok && type.includes('json')) status = await r.json();
    else console.log(`  not answering yet (HTTP ${r.status}), trying again in 10 seconds...`);
  } catch (e) {
    console.log(`  not answering yet (${e.message}), trying again in 10 seconds...`);
  }
  if (!status) await new Promise((done) => setTimeout(done, 10000));
}
if (!status) fail('the Worker deployed but hoopsmatic.com/how-to-watch/live/ did not answer. Tell Claude.');

console.log(JSON.stringify(status, null, 1));
console.log('');
if (status.state === 'ok' || status.state === 'serving the last good copy') {
  console.log(`IT WORKS. Live availability updated ${status.updated_at}, ${status.games_today} games today, ` +
    `${status.players_listed} players listed. The pages now read from the Worker.`);
} else if (status.state === 'no games today') {
  console.log('IT WORKS. No games today, so there is nothing to serve; the pages use the build\'s copy until the next game day.');
} else {
  console.log(`DEPLOYED, BUT NOT SERVING YET: ${status.state}${status.error ? ' (' + status.error + ')' : ''}. Tell Claude.`);
}
